-- Identitas wilayah Kwarran, penetapan Admin Kwarran, dan ringkasan perbandingan.
-- Data pangkalan lama sengaja tidak dipetakan otomatis; Admin Utama menentukan wilayahnya.

alter type public.app_role add value if not exists 'admin_kwarran';

create table if not exists public.kwarran (
  id_kwarran bigint generated by default as identity primary key,
  nama_kwarran text not null unique check (length(btrim(nama_kwarran)) > 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.admin_kwarran (
  id_user uuid primary key references public.users(id_user) on delete cascade,
  id_kwarran bigint not null references public.kwarran(id_kwarran) on delete restrict,
  nama_lengkap text,
  created_at timestamptz not null default now(),
  assigned_by uuid references public.users(id_user) on delete set null
);

alter table public.admin_kwarran add column if not exists nama_lengkap text;
alter table public.pangkalan
  add column if not exists id_kwarran bigint references public.kwarran(id_kwarran) on delete restrict;

create index if not exists pangkalan_id_kwarran_idx on public.pangkalan(id_kwarran);
create index if not exists admin_kwarran_id_kwarran_idx on public.admin_kwarran(id_kwarran);
create index if not exists admin_kwarran_assigned_by_idx on public.admin_kwarran(assigned_by);

alter table public.kwarran enable row level security;
alter table public.admin_kwarran enable row level security;

revoke all on public.kwarran from anon, authenticated;
revoke all on public.admin_kwarran from anon, authenticated;
grant select, insert, update, delete on public.kwarran to service_role;
grant select, insert, update, delete on public.admin_kwarran to service_role;
grant usage, select on sequence public.kwarran_id_kwarran_seq to service_role;

create or replace view public.v_kwarran_comparison
with (security_invoker=true) as
select
  k.id_kwarran,
  k.nama_kwarran,
  count(distinct p.id_pangkalan)::integer as jumlah_pangkalan,
  count(r.id_pangkalan)::integer as jumlah_ambalan,
  coalesce(sum(r.jumlah_peserta),0)::integer as jumlah_peserta,
  coalesce(sum(r.peserta_aktif),0)::integer as peserta_aktif,
  coalesce(sum(r.menunggu_persetujuan),0)::integer as menunggu_persetujuan,
  coalesce(sum(r.calon_penegak),0)::integer as calon_penegak,
  coalesce(sum(r.bantara),0)::integer as bantara,
  coalesce(sum(r.laksana),0)::integer as laksana,
  coalesce(sum(r.garuda),0)::integer as garuda,
  coalesce(sum(r.jumlah_alumni),0)::integer as jumlah_alumni
from public.kwarran k
left join public.pangkalan p on p.id_kwarran=k.id_kwarran
left join public.v_admin_ambalan_rekap r on r.id_pangkalan=p.id_pangkalan
group by k.id_kwarran,k.nama_kwarran;

revoke all on public.v_kwarran_comparison from anon, authenticated;
grant select on public.v_kwarran_comparison to service_role;

comment on table public.kwarran is 'Master wilayah Kwarran untuk pemisahan dan perbandingan data RUANG TEGAK.';
comment on table public.admin_kwarran is 'Penetapan satu akun Admin Kwarran ke satu wilayah Kwarran.';
comment on column public.pangkalan.id_kwarran is 'Wilayah Kwarran pemilik pangkalan; null sampai dipetakan Admin Utama.';
comment on view public.v_kwarran_comparison is 'Ringkasan agregat antarkwarran tanpa identitas atau data pribadi peserta didik.';
